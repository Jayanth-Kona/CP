#include<bits/stdc++.h>
using namespace std;
using ll = long long;

int main(){
    ll n , q ; cin >> n >> q;

    vector<ll> a(n + 1) , s(n + 1) , p(n + 1);
    a[0] = s[0] = p[0] = 0;

    for(int i = 1 ; i <= n ; i++){
        cin >> a[i];
        s[i] = s[i - 1] + a[i];
        p[i] = p[i - 1] + s[i];
    }

    auto sum = [&](ll index) -> ll{
        int i = (-1 + sqrtl(1 + 8 * index)) / 2;
        int j = index - (i * 1LL * (i + 1) / 2);
        return p[i] + s[j];
    };

    while(q--){
        ll l , r ; cin >> l >> r;
        cout << sum(r) - sum(l - 1) << '\n';
    }

    return 0;
}


